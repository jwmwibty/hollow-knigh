package com.devdgames.hollowknightbutmine.game.world

/**
 * The kingdom, authored as one connected tile world.
 *
 * Layout (tile coordinates, 40px per tile). Read it like the Hallownest map: the surface
 * town sits on top, the well drops into the Crossroads hub, and every other region hangs
 * off that hub - west into the green caves and the fungal hollows, east into the crystal
 * mines and the resting grounds, down through the city of rain into the waterways, the
 * deep nest and the ancient basin, and finally the abyss at the very bottom.
 *
 *            x: 0        36        50        60         106       140
 *   y:   0    [ Cliffs ][ Dustmere town   ]            [ Glimmer Peak   ]
 *       18    [ Cliffs ][ Forgotten Crossroads        ][ Resting Grnds ]
 *       34    [Verdant ][ Crossroads                  ][ Ashen Edge    ]
 *       50    [ Path   ]        [ City of Rain        ][ Ashen Edge    ]
 *       66    [ Fungal Hollows ][ City of Rain        ][ Ashen Edge    ]
 *       92    [ Silk Deep      ][ Old Waterways       ][ Ashen Edge    ]
 *      108    [ Silk Deep      ][ Ancient Basin                        ]
 *      130                          [ The Abyss      ]
 *
 * East wing: a doorway in the Resting Grounds' east wall leads to the Vigil Hall (the Keener),
 * and one in Glimmer Peak's east wall to the Geode Court (Shardback). Both are dead-end boss
 * halls, each with a bench in its antechamber; the encounters live in game/boss/.
 *
 * Every opening on an area border lines up with an opening on its neighbour; the
 * [WorldLayout] validator checks this, so if you edit a map and break a passage you
 * will get a clear error listing the exact tile.
 *
 * Climbing shafts are 5 tiles wide with staggered 1-tile ledges on alternating walls:
 * a falling player drops straight through the middle, while a climbing player can hop
 * from ledge to ledge back up. Double jump clears 5 rows, single jump clears 2.
 */
